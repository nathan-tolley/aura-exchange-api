CREATE TABLE IF NOT EXISTS market_price_ticks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  season_id uuid NOT NULL REFERENCES seasons(id),
  stock_id uuid NOT NULL REFERENCES person_stocks(id),
  price numeric(20,8) NOT NULL CHECK (price > 0),
  cause text NOT NULL CHECK (cause IN ('OPEN', 'TRADE', 'AMBIENT')),
  reference_id uuid,
  is_synthetic boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS market_price_ticks_stock_time_idx
  ON market_price_ticks(stock_id, season_id, created_at);

-- Give newly upgraded markets enough explicitly synthetic tape to render useful
-- candles immediately. Future points are generated by the worker.
INSERT INTO market_price_ticks(season_id, stock_id, price, cause, is_synthetic, created_at)
SELECT mp.season_id,
       mp.stock_id,
       (mp.organic_price * (1 +
         sin(extract(epoch FROM sample.at) / 1700 + abs(hashtext(mp.stock_id::text) % 1000) / 91.0) * 0.0018 +
         cos(extract(epoch FROM sample.at) / 3100 + abs(hashtext(mp.stock_id::text) % 1000) / 137.0) * 0.0009
       ))::numeric(20,8),
       'AMBIENT',
       true,
       sample.at
  FROM market_pools mp
  JOIN seasons s ON s.id=mp.season_id AND s.status='ACTIVE'
 CROSS JOIN LATERAL generate_series(
       GREATEST(s.starts_at, now() - interval '24 hours'),
       now() - interval '15 minutes',
       interval '15 minutes'
     ) AS sample(at)
 WHERE NOT EXISTS (
   SELECT 1 FROM market_price_ticks existing
    WHERE existing.season_id=mp.season_id AND existing.stock_id=mp.stock_id
 );

